  const next = {...first,latestObservedPosition:10,observedLap:8,gapToLeaderSeconds:.7,intervalSeconds:.3,bestLapSeconds:126}
  const payload=(row:typeof first)=>({sessionId:'S',mode:'event',rows:[row],metadata:{rowCount:1,sourceMode:'LIVE'}})
