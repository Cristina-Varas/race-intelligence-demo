it.each(['xlsx', 'csv'] as const)('downloads backend %s bytes with the session filename', async (format) => {
  const fetchMock = vi.fn().mockResolvedValue({ ok: true, blob: async () => new Blob(['backend artifact']) })
  vi.stubGlobal('fetch', fetchMock)
  const objectURL = vi.fn().mockReturnValue('blob:download')
  vi.stubGlobal('URL', Object.assign(class extends URL {}, { createObjectURL: objectURL, revokeObjectURL: vi.fn() }))
  let filename = ''
  vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(function (this: HTMLAnchorElement) { filename = this.download })
  await mount(); fireEvent.click(screen.getByRole('button', { name: `DOWNLOAD ${format.toUpperCase()}` }))
  await waitFor(() => expect(filename).toBe(`REHEARSAL_LIVE_CHECK_card_data.${format}`))
  expect(fetchMock).toHaveBeenCalledWith(expect.stringContaining(`/baseball-card-data.${format}?mode=event`), undefined)
  expect(objectURL).toHaveBeenCalledWith(expect.any(Blob))
  await waitFor(() => expect(URL.revokeObjectURL).toHaveBeenCalled(), { timeout: 2500 })
})
